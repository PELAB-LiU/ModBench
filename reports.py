def get_artifact_sizes() -> dict[str, str]:
    if USE_REMOTE:
        targets = {
            "MbStorePipelineDbSize":   f"{REMOTE_BASE}/dataset/pipeline.db",
            "MbStoreClassEnumDbSize":  f"{REMOTE_BASE}/dataset/step2_classes.db",
            "MbStoreCanonicalDirSize": f"{REMOTE_BASE}/dataset/canonical_models/MSL",
        }
    else:
        targets = {
            "MbStorePipelineDbSize":   PIPELINE_DB_LOCAL,
            "MbStoreClassEnumDbSize":  STEP2_DB_LOCAL,
            "MbStoreCanonicalDirSize": CANONICAL_DIR_LOCAL,
        }
    out: dict[str, str] = {}
    for var, path in targets.items():
        try:
            if USE_REMOTE:
                res = subprocess.run(
                    ["ssh", REMOTE_HOST, f'du -sh "{path}" | cut -f1'],
                    capture_output=True, text=True, timeout=120,
                )
            else:
                res = subprocess.run(
                    f'du -sh "{path}" | cut -f1',
                    shell=True, capture_output=True, text=True, timeout=120,
                )
            if res.returncode != 0:
                print(f"[WARN] du failed for {var}: {res.stderr.strip()}")
                continue
            m = re.match(r"([\d.]+)([KMGT]?)", res.stdout.strip())
            if not m:
                continue
            num, unit = m.groups()
            unit_map = {"K": "KB", "M": "MB", "G": "GB", "T": "TB", "": "B"}
            out[var] = num + r"\," + unit_map[unit]
        except Exception as e:
            print(f"[WARN] Could not measure {var}: {e}")
    return out


# ---------------------------------------------------------------------------
# Step 2 timeline figure (papers/SAM2026/figs/step2_classes_timeline.png)
# ---------------------------------------------------------------------------


def _get_commit_dates(commit_hashes: list[str]) -> dict[str, str]:
    repo_path = LOCAL_SOURCE_DIR / SOURCE_NAME
    if not repo_path.exists():
        print(f"[WARN] Local repo not found at {repo_path}, skipping date resolution")
        return {}
    try:
        import git as gitpython  # type: ignore
    except ImportError:
        print("[WARN] gitpython not installed, skipping date resolution")
        return {}
    try:
        repo = gitpython.Repo(repo_path)
    except Exception as e:
        print(f"[WARN] Cannot open repo: {e}")
        return {}
    wanted = set(commit_hashes)
    dates: dict[str, str] = {}
    for c in repo.iter_commits("--all", max_count=50_000):
        if c.hexsha in wanted:
            dates[c.hexsha] = datetime.fromtimestamp(
                c.committed_date, tz=timezone.utc,
            ).strftime("%Y-%m-%d")
            wanted.discard(c.hexsha)
            if not wanted:
                break
    return dates


def plot_step2_timeline(per_commit_rows: list[dict[str, str]],
                        commit_hashes: list[str]) -> None:
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        import numpy as np
    except ImportError:
        print("[WARN] matplotlib/numpy not installed, skipping figure.")
        return

    dates = _get_commit_dates(commit_hashes)
    if len(dates) < 10:
        print(f"[WARN] Only {len(dates)} commit dates resolved, skipping figure.")
        return

    series = []
    for r in per_commit_rows:
        d = dates.get(r["commit_hash"])
        if d:
            series.append((d, _int(r["total_classes"]), _int(r["experiment_classes"])))
    series.sort(key=lambda x: x[0])
    if len(series) < 10:
        print("[WARN] Insufficient time-series data, skipping figure.")
        return

    plot_dates = [datetime.strptime(d, "%Y-%m-%d") for d, _, _ in series]
    totals = [t for _, t, _ in series]
    experiments = [e for _, _, e in series]

    fig, (ax_top, ax_bot) = plt.subplots(
        2, 1, figsize=(7, 4.5), dpi=160, sharex=True,
        gridspec_kw={"hspace": 0.15},
    )
    window = min(50, len(totals) // 5) if len(totals) > 10 else 1
    kernel = np.ones(window) / window if window > 1 else None
    offset = window // 2

    ax_top.scatter(plot_dates, totals, s=2, alpha=0.25, color="#1f77b4")
    if kernel is not None:
        smooth = np.convolve(totals, kernel, mode="valid")
        ax_top.plot(plot_dates[offset: offset + len(smooth)],
                    smooth, color="#1f77b4", linewidth=1.5)
    ax_top.axhline(mean(totals), color="#1f77b4", linestyle="--",
                   linewidth=0.8, alpha=0.6)
    ax_top.set_ylabel("All classes", fontsize=10)
    ax_top.grid(True, alpha=0.3)
    ax_top.set_title("MSL class population per processed commit", fontsize=10)

    ax_bot.scatter(plot_dates, experiments, s=2, alpha=0.25, color="#ff7f0e")
    if kernel is not None:
        smooth_e = np.convolve(experiments, kernel, mode="valid")
        ax_bot.plot(plot_dates[offset: offset + len(smooth_e)],
                    smooth_e, color="#ff7f0e", linewidth=1.5)
    ax_bot.axhline(mean(experiments), color="#ff7f0e", linestyle="--",
                   linewidth=0.8, alpha=0.6)
    ax_bot.set_ylabel("Simulation-eligible classes", fontsize=10)
    ax_bot.set_xlabel("Commit date")
    ax_bot.grid(True, alpha=0.3)
    ax_top.yaxis.set_label_coords(-0.09, 0.5)
    ax_bot.yaxis.set_label_coords(-0.09, 0.5)

    fig.autofmt_xdate()
    fig.tight_layout()
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    out_path = FIG_DIR / "step2_classes_timeline.png"
    fig.savefig(out_path, bbox_inches="tight")
    plt.close(fig)
    print(f"  Saved {out_path}")


# ---------------------------------------------------------------------------
# variables.tex update (in-place rewriting of \newcommand values)
# ---------------------------------------------------------------------------

_NEWCOMMAND_RE = re.compile(r"^(\s*\\newcommand\{\\)([A-Za-z]+)\}\{")


def _parse_newcommand(line: str):
    m = _NEWCOMMAND_RE.match(line)
    if not m:
        return None
    prefix, name = m.group(1), m.group(2)
    i, depth = m.end(), 1
    while i < len(line) and depth > 0:
        if line[i] == "{":
            depth += 1
        elif line[i] == "}":
            depth -= 1
        i += 1
    if depth != 0:
        return None
    return prefix, name, line[m.end(): i - 1], line[i - 1:]


def update_variables_tex(values: dict[str, str]) -> tuple[int, int, set[str]]:
    """Update values in ``variables.tex`` in place.

    Returns ``(macro_count, updated_count, defined_macros)``. Aliased
    macros (whose value starts with ``\\``) are skipped because their
    value is another macro, not a literal.
    """
    text = VARIABLES_TEX.read_text(encoding="utf-8")
    lines = text.splitlines()
    new_lines: list[str] = []
    defined: set[str] = set()
    updated = 0

    for line in lines:
        parsed = _parse_newcommand(line)
        if parsed is None:
            new_lines.append(line)
            continue
        prefix, name, current, suffix = parsed
        defined.add(name)
        new_value = values.get(name)
        # Skip alias-style definitions ("\MbFoo") -- don't overwrite.
        if new_value is not None and not current.startswith("\\") \
                and new_value != current:
            new_lines.append(prefix + name + "}{" + new_value + suffix)
            updated += 1
        else:
            new_lines.append(line)

    VARIABLES_TEX.write_text("\n".join(new_lines) + "\n", encoding="utf-8")
    return len(defined), updated, defined


def _get_pilot_settings() -> dict[str, str]:
    """Read Step-3 pilot-mode configuration from ``run_settings``.

    Returns a mapping like ``{"PILOT_ENABLED": "1", ...}``. Empty when
    the table has no Step-3 rows (older runs).
    """
    try:
        rows = _run_sql(
            ACTIVE_PIPELINE_DB,
            "SELECT key, value FROM run_settings WHERE pipeline_step_number=3",
        )
    except Exception:
        return {}
    return {r["key"]: r["value"] for r in rows}


def _get_step3_commit_progress() -> dict[str, int]:
    try:
        rows = _run_sql(
            ACTIVE_PIPELINE_DB,
            f"SELECT status, COUNT(*) AS cnt FROM step3_commit_progress "
            f"WHERE source_name='{SOURCE_NAME}' GROUP BY status",
        )
    except Exception:
        return {}
    return {r["status"]: int(r["cnt"]) for r in rows}


