def _is_figure_only(argv: list[str]) -> bool:
    return "--figure-only" in argv


def _is_pilot_allowed(argv: list[str]) -> bool:
    """Explicit opt-in required to publish pilot-run numbers."""
    return "--allow-pilot" in argv


def _abort_if_pilot(argv: list[str]) -> dict[str, str]:
    """Read Step-3 pilot settings and abort unless ``--allow-pilot``.

    Returns the settings dict on success. Never returns when aborting.
    """
    pilot = _get_pilot_settings()
    enabled = pilot.get("PILOT_ENABLED", "0") in {"1", "true", "True"}
    if not enabled:
        return pilot
    if _is_pilot_allowed(argv):
        print("[WARN] Step 3 was run in PILOT mode -- proceeding because "
              "--allow-pilot was given.")
        for k, v in sorted(pilot.items()):
            print(f"         {k} = {v!r}")
        return pilot
    print("=" * 60)
    print("  ABORT: Step 3 was run in PILOT mode.")
    print("=" * 60)
    print("  Pilot mode canonicalises only a bounded sample of")
    print("  experiment classes per commit, so the resulting Step-3")
    print("  numbers are NOT representative of the full population.")
    print("  variables.tex and figures were NOT modified.")
    print()
    print("  run_settings (pipeline_step_number=3):")
    for k, v in sorted(pilot.items()):
        print(f"    {k} = {v!r}")
    print()
    print("  To publish pilot numbers anyway, re-run with --allow-pilot.")
    print("  To publish full numbers, re-run Step 3 with PILOT_ENABLED=0.")
    sys.exit(2)


def main() -> None:
    figure_only = _is_figure_only(sys.argv[1:])

    print("=" * 60)
    print("  SAM2026 Paper -- Report Generator (MSL only)")
    print("=" * 60)
    if USE_REMOTE:
        print(f"  Mode:        remote (ssh {REMOTE_HOST})")
        print(f"  Remote base: {REMOTE_BASE}")
    else:
        print("  Mode:        local")
        print(f"  Pipeline DB: {PIPELINE_DB_LOCAL}")
        print(f"  Step2 DB:    {STEP2_DB_LOCAL}")
    print(f"  variables.tex: {VARIABLES_TEX}")
    print()

    # Refuse to update anything with pilot-run data unless opted in.
    pilot = _abort_if_pilot(sys.argv[1:])

    if figure_only:
        print("[FIGS] Figure-only mode: regenerating step2 timeline...")
        _, per_commit = analyze_step2()
        plot_step2_timeline(per_commit, [r["commit_hash"] for r in per_commit])
        print("\nDone.")
        return

    values: dict[str, str] = dict(STATIC_VALUES)

    print("[STEP 1] Commit filtering...")
    values.update(analyze_step1())
    print(f"         Retained: {values['MbFilterRetained']}")

    print("\n[STEP 2] Class enumeration...")
    step2_vals, per_commit = analyze_step2()
    values.update(step2_vals)
    print(f"         Experiment versions: {step2_vals['MbListExperimentVersions']}")

    step2_failed_commits = _count_step2_failed_commits()
    print(f"         Step-2 commit-level load failures "
          f"(retained by Step 1, no step2_classes rows): {step2_failed_commits:,}")

    print("\n[STEP 3] Canonicalisation...")
    extra_load = _count_commit_level_load_failures()
    print(f"         Commit-level package-load failures (folded in): {extra_load}")
    values.update(analyze_step3(extra_load_failures=extra_load))
    print(f"         Produced: {values['MbCanonProducedVersions']}, "
          f"Failures: {values['MbCanonFailures']}")

    print("\n[SIZES] Artifact sizes...")
    values.update(get_artifact_sizes())
    for k in ("MbStorePipelineDbSize", "MbStoreClassEnumDbSize",
              "MbStoreCanonicalDirSize"):
        if k in values:
            print(f"         {k} = {values[k]}")

    print("\n[FAILURES] Canonicalisation failure analysis...")
    categories, total_failures = analyze_failures(extra_load_failures=extra_load)
    print(f"         Total: {total_failures}")
    for cat, cnt in sorted(categories.items(), key=lambda x: -x[1]):
        print(f"           {cat:36s} {cnt:>7,}  ({_pct(cnt, total_failures):.1f}%)")
    # Default every failure-category macro to 0 so variables.tex is
    # always fully populated even when a category has no matches.
    for cnt_var, pct_var in FAILURE_CATEGORY_VARS.values():
        values.setdefault(cnt_var, _fmt_int(0))
        values.setdefault(pct_var, "0.0")
    for cat, cnt in categories.items():
        if cat in FAILURE_CATEGORY_VARS:
            cnt_var, pct_var = FAILURE_CATEGORY_VARS[cat]
            values[cnt_var] = _fmt_int(cnt)
            values[pct_var] = f"{_pct(cnt, total_failures):.1f}"

    # Verify we computed exactly the right macros: no surprises, no gaps.
    produced_vars = set(values)
    extra = produced_vars - EXPECTED_VARS
    missing = EXPECTED_VARS - produced_vars
    if extra:
        print(f"\n[WARN] Computed but not expected by body.tex: {sorted(extra)}")
    if missing:
        print(f"\n[WARN] Expected by body.tex but not computed: {sorted(missing)}")

    print("\n[TEX] Updating variables.tex...")
    total, updated, defined = update_variables_tex(values)
    print(f"       Macros in variables.tex: {total}, updated this run: {updated}")
    stray_defined = defined - EXPECTED_VARS - {"MbListProcessedCommits",
                                               "MbCanonInputVersions"}
    if stray_defined:
        print(f"[WARN] Defined but unused in body.tex: {sorted(stray_defined)}")

    print("\n[FIGS] Generating step2 timeline figure...")
    plot_step2_timeline(per_commit, [r["commit_hash"] for r in per_commit])

    print("\n[SANITY] Cross-cutting invariants...")
    pilot = _get_pilot_settings()
    step3_progress = _get_step3_commit_progress()
    nfail = run_sanity_checks(values, categories, extra_load,
                              step2_failed_commits=step2_failed_commits,
                              pilot=pilot, step3_progress=step3_progress)
    print(f"  -> {'all checks passed' if nfail == 0 else f'{nfail} check(s) FAILED'}")

    print("\n" + "=" * 60)
    print("  Done. See papers/SAM2026/variables.tex and figs/.")
    print("=" * 60)


if __name__ == "__main__":
    main()

