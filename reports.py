# ---------------------------------------------------------------------------
# Small helpers
# ---------------------------------------------------------------------------


def _pct(n: int, d: int) -> float:
    return (100.0 * n / d) if d else 0.0


def _fmt_int(n: int) -> str:
    """Format integer with LaTeX-safe thousand separators."""
    return f"{n:,}".replace(",", "{,}")


def _int(s: str) -> int:
    return int((s or "0").replace(",", "").strip() or "0")


# ---------------------------------------------------------------------------
# SQL execution (local sqlite3 CLI or remote over SSH)
# ---------------------------------------------------------------------------


def _run_sql(db_path: str, sql: str, timeout: int = 300) -> list[dict[str, str]]:
    if USE_REMOTE:
        cmd = ["ssh", REMOTE_HOST, f'sqlite3 -header -csv "{db_path}" "{sql}"']
    else:
        cmd = ["sqlite3", "-header", "-csv", db_path, sql]
    res = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
    if res.returncode != 0:
        raise RuntimeError(
            f"SQL failed on {db_path}: {res.stderr.strip()}\nSQL: {sql}"
        )
    out = res.stdout.strip()
    if not out:
        return []
    return list(csv.DictReader(io.StringIO(out)))


def _sql_scalar(db_path: str, sql: str) -> str:
    rows = _run_sql(db_path, sql)
    if not rows:
        return "0"
    return next(iter(rows[0].values()))


# ---------------------------------------------------------------------------
# Step 1: commit filtering funnel
# ---------------------------------------------------------------------------


def analyze_step1() -> dict[str, str]:
    print("  Querying step1_commits...")
    total = _int(_sql_scalar(
        ACTIVE_PIPELINE_DB,
        f"SELECT COUNT(*) FROM step1_commits WHERE source_name='{SOURCE_NAME}'",
    ))
    retained = _int(_sql_scalar(
        ACTIVE_PIPELINE_DB,
        f"SELECT COUNT(*) FROM step1_commits "
        f"WHERE source_name='{SOURCE_NAME}' AND excluded=0",
    ))
    rows = _run_sql(
        ACTIVE_PIPELINE_DB,
        f"SELECT exclusion_reason, COUNT(*) AS cnt FROM step1_commits "
        f"WHERE source_name='{SOURCE_NAME}' AND excluded=1 "
        f"GROUP BY exclusion_reason",
    )

    excl_branches = excl_pre_v3 = excl_bot = excl_no_mo = 0
    for r in rows:
        reason = (r.get("exclusion_reason") or "").lower()
        cnt = int(r["cnt"])
        if "excluded branch" in reason:
            excl_branches += cnt
        elif "before tag" in reason:
            excl_pre_v3 += cnt
        elif "no .mo files" in reason:
            excl_no_mo += cnt
        elif any(k in reason for k in (
            "bot", "commit message matches",
            "author name contains", "author email contains",
        )):
            excl_bot += cnt

    return {
        "MbFilterInputCommits":   _fmt_int(total),
        "MbFilterExclBranches":   _fmt_int(excl_branches),
        "MbFilterAfterBranches":  _fmt_int(total - excl_branches),
        "MbFilterExclPreVThree":  _fmt_int(excl_pre_v3),
        "MbFilterAfterPreVThree": _fmt_int(total - excl_branches - excl_pre_v3),
        "MbFilterExclBot":        _fmt_int(excl_bot),
        "MbFilterAfterBot":       _fmt_int(total - excl_branches - excl_pre_v3 - excl_bot),
        "MbFilterExclNoMo":       _fmt_int(excl_no_mo),
        "MbFilterRetained":       _fmt_int(retained),
        "MbFilterRetainedPct":    f"{_pct(retained, total):.1f}",
    }


# ---------------------------------------------------------------------------
# Step 2: class enumeration
# ---------------------------------------------------------------------------


def analyze_step2() -> tuple[dict[str, str], list[dict[str, str]]]:
    print("  Querying step2_classes (summary)...")
    s = _run_sql(
        ACTIVE_STEP2_DB,
        f"SELECT COUNT(*) AS total_rows, "
        f"COUNT(DISTINCT class_name) AS unique_classes, "
        f"SUM(CASE WHEN is_experiment=1 THEN 1 ELSE 0 END) AS exp_rows, "
        f"SUM(CASE WHEN is_experiment=0 THEN 1 ELSE 0 END) AS nonexp_rows "
        f"FROM step2_classes WHERE source_name='{SOURCE_NAME}'",
    )[0]
    total_rows = _int(s["total_rows"])
    unique_classes = _int(s["unique_classes"])
    exp_rows = _int(s["exp_rows"])
    nonexp_rows = _int(s["nonexp_rows"])

    print("  Querying per-commit breakdown (may take a while)...")
    per_commit = _run_sql(
        ACTIVE_STEP2_DB,
        f"SELECT commit_hash, COUNT(*) AS total_classes, "
        f"SUM(CASE WHEN is_experiment=1 THEN 1 ELSE 0 END) AS experiment_classes "
        f"FROM step2_classes WHERE source_name='{SOURCE_NAME}' "
        f"GROUP BY commit_hash",
        timeout=600,
    )
    totals = [_int(r["total_classes"]) for r in per_commit]
    experiments = [_int(r["experiment_classes"]) for r in per_commit]
    ratios = [e / t if t else 0.0 for t, e in zip(totals, experiments)]

    values = {
        "MbListDistinctClassNames":     _fmt_int(unique_classes),
        "MbListAllClassVersions":       _fmt_int(total_rows),
        "MbListNonExperimentVersions":  _fmt_int(nonexp_rows),
        "MbListNonExperimentPct":       f"{_pct(nonexp_rows, total_rows):.1f}",
        "MbListExperimentVersions":     _fmt_int(exp_rows),
        "MbListExperimentPct":          f"{_pct(exp_rows, total_rows):.1f}",
        "MbListMaxExperimentPerCommit": str(max(experiments)) if experiments else "0",
        "MbGrowthAllClassMean":         _fmt_int(round(mean(totals))) if totals else "0",
        "MbGrowthExperimentMean":       str(round(mean(experiments))) if experiments else "0",
        "MbGrowthExperimentRatioMean":  f"{mean(ratios) * 100:.1f}" if ratios else "0",
    }
    return values, per_commit


