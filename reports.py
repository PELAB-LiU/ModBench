# Step 3: canonicalisation
# ---------------------------------------------------------------------------


def _count_step2_failed_commits() -> int:
    """Count Step-1-retained commits with zero rows in step2_classes.

    These are commits that Step 2 *walked* (its progress bar ticked) but for
    which class enumeration produced no rows -- typically because
    ``git checkout`` failed on a historical revision, ``loadFile`` of the
    MSL package failed under the current OMC, or ``getClassNames`` returned
    empty. They are commit-level Step-2 load failures and would otherwise be
    invisible to the report (they don't show up in step2_classes, step3_classes,
    or step3_failures).

    We keep them as a *separate* count (in commits) rather than folding into
    ``MbCanonFailures`` (which counts experiment-class versions) so that the
    Step-3 invariants stay clean.
    """
    sql = (
        f"ATTACH '{ACTIVE_STEP2_DB}' AS s2; "
        f"SELECT COUNT(*) FROM step1_commits "
        f"WHERE source_name='{SOURCE_NAME}' AND excluded=0 "
        f"  AND commit_hash NOT IN ("
        f"    SELECT DISTINCT commit_hash FROM s2.step2_classes "
        f"    WHERE source_name='{SOURCE_NAME}'"
        f"  );"
    )
    return _int(_sql_scalar(ACTIVE_PIPELINE_DB, sql))


def _count_commit_level_load_failures() -> int:
    """Count step2 experiment-class rows whose commit produced zero step3 rows.

    Step3 records package-load failures in ``step3_failures`` with an empty
    ``class_name`` and never inserts per-class rows in ``step3_classes`` for
    that commit. We attribute the full per-commit experiment count of each
    such commit to the failure bucket so totals reconcile with
    ``MbListExperimentVersions``.
    """
    sql = (
        f"ATTACH '{ACTIVE_PIPELINE_DB}' AS pl; "
        f"SELECT COALESCE(SUM(cnt), 0) FROM ("
        f"  SELECT commit_hash, COUNT(*) AS cnt "
        f"  FROM step2_classes "
        f"  WHERE source_name='{SOURCE_NAME}' AND is_experiment=1 "
        f"    AND commit_hash NOT IN ("
        f"      SELECT DISTINCT commit_hash FROM pl.step3_classes "
        f"      WHERE source_name='{SOURCE_NAME}'"
        f"    ) "
        f"  GROUP BY commit_hash"
        f");"
    )
    return _int(_sql_scalar(ACTIVE_STEP2_DB, sql))


def analyze_step3(extra_load_failures: int = 0) -> dict[str, str]:
    print("  Querying step3_classes...")
    s = _run_sql(
        ACTIVE_PIPELINE_DB,
        f"SELECT SUM(CASE WHEN canonical_produced=1 THEN 1 ELSE 0 END) AS produced, "
        f"SUM(CASE WHEN canonical_produced=0 THEN 1 ELSE 0 END) AS failed "
        f"FROM step3_classes WHERE source_name='{SOURCE_NAME}'",
    )[0]
    produced = _int(s["produced"])
    failures = _int(s["failed"]) + extra_load_failures
    processed = produced + failures

    commits_with_exp = _int(_sql_scalar(
        ACTIVE_STEP2_DB,
        f"SELECT COUNT(DISTINCT commit_hash) FROM step2_classes "
        f"WHERE source_name='{SOURCE_NAME}' AND is_experiment=1",
    ))
    total_retained = _int(_sql_scalar(
        ACTIVE_PIPELINE_DB,
        f"SELECT COUNT(*) FROM step1_commits "
        f"WHERE source_name='{SOURCE_NAME}' AND excluded=0",
    ))

    return {
        "MbCanonCommitsWithExperiment":    _fmt_int(commits_with_exp),
        "MbCanonCommitsWithExperimentPct": f"{_pct(commits_with_exp, total_retained):.1f}",
        "MbCanonProducedVersions":         _fmt_int(produced),
        "MbCanonProducedPct":              f"{_pct(produced, processed):.1f}",
        "MbCanonFailures":                 _fmt_int(failures),
        "MbCanonFailuresPct":              f"{_pct(failures, processed):.1f}",
    }


# ---------------------------------------------------------------------------
# Failure analysis (categorise step3_classes error messages)
# ---------------------------------------------------------------------------

FAILURE_PATTERNS: list[tuple[str, str]] = [
    (r"(?i)loadFile|loadModel|could not (load|open)|package.*not found|failed to load",
     "Package load failure"),
    (r"(?i)extends.*not found|base.?class.*not|could not find.*base|unknown base",
     "Missing base class"),
    (r"(?i)class.*not found|not found in scope|could not find class|unknown class|lookup.*failed",
     "Missing referenced class"),
    (r"(?i)replaceable|redeclare|redeclaration|not replaceable",
     "Replaceable/redeclare conflict"),
    (r"(?i)restriction|operator.?record|illegal.*operator",
     "Operator-record restriction"),
    (r"(?i)type\s+error|type.*mismatch|incompatible.*type",
     "Type mismatch"),
    (r"(?i)savetotalmodel|save.*total.*model|timeout|timed out",
     "Canonicalization timeout"),
    (r"(?i)syntax|parse\s*error|unexpected token",
     "Syntax error"),
]

# Categories that map to LaTeX macros referenced in body.tex.
FAILURE_CATEGORY_VARS: dict[str, tuple[str, str]] = {
    "Operator-record restriction":    ("MbFailOperatorRestriction",   "MbFailOperatorRestrictionPct"),
    "Missing referenced class":       ("MbFailMissingClass",          "MbFailMissingClassPct"),
    "Replaceable/redeclare conflict": ("MbFailRedeclare",             "MbFailRedeclarePct"),
    "Missing base class":             ("MbFailMissingBase",           "MbFailMissingBasePct"),
    "Canonicalization timeout":       ("MbFailTimeout",               "MbFailTimeoutPct"),
    "Package load failure":           ("MbFailPackageLoad",           "MbFailPackageLoadPct"),
}


def analyze_failures(extra_load_failures: int = 0) -> tuple[dict[str, int], int]:
    print("  Querying failure error messages...")
    rows = _run_sql(
        ACTIVE_PIPELINE_DB,
        f"SELECT error_message FROM step3_classes "
        f"WHERE source_name='{SOURCE_NAME}' AND canonical_produced=0 "
        f"AND error_message!=''",
        timeout=600,
    )
    total = len(rows)
    categories: Counter = Counter()
    for r in rows:
        msg = (r.get("error_message") or "").strip()
        if not msg:
            categories["Empty error / unknown"] += 1
            continue
        for pattern, label in FAILURE_PATTERNS:
            if re.search(pattern, msg):
                categories[label] += 1
                break
        else:
            categories["Other"] += 1

    if extra_load_failures:
        categories["Package load failure"] += extra_load_failures
        total += extra_load_failures
    return dict(categories.most_common()), total


