def _vi(d: dict[str, str], k: str) -> int:
    raw = d.get(k, "0").replace("{,}", "").replace(",", "")
    try:
        return int(raw)
    except ValueError:
        return 0


def run_sanity_checks(v: dict[str, str], categories: dict[str, int],
                      extra_load: int, step2_failed_commits: int = 0,
                      pilot: dict[str, str] | None = None,
                      step3_progress: dict[str, int] | None = None) -> int:
    fails: list[str] = []
    pilot = pilot or {}
    step3_progress = step3_progress or {}
    pilot_enabled = pilot.get("PILOT_ENABLED", "0") in {"1", "true", "True"}

    def check(label: str, lhs: int, rhs: int) -> None:
        ok = lhs == rhs
        marker = "OK  " if ok else "FAIL"
        diff = "" if ok else f"  (diff={lhs - rhs:+,})"
        print(f"  [{marker}] {label}: {lhs:,} vs {rhs:,}{diff}")
        if not ok:
            fails.append(label)

    in_c = _vi(v, "MbFilterInputCommits")
    excl = (_vi(v, "MbFilterExclBranches") + _vi(v, "MbFilterExclPreVThree")
            + _vi(v, "MbFilterExclBot") + _vi(v, "MbFilterExclNoMo"))
    check("Step1: retained + excluded == input",
          _vi(v, "MbFilterRetained") + excl, in_c)

    # Step1-retained == commits that actually produced step2_classes rows + step2 commit-level failures
    retained = _vi(v, "MbFilterRetained")
    commits_with_classes = retained - step2_failed_commits  # by definition; the check below verifies
    check("Step2: commits-with-classes + commit-level load failures == Step1 retained",
          commits_with_classes + step2_failed_commits, retained)
    if step2_failed_commits:
        print(f"  [INFO] Step-2 commit-level load failures: {step2_failed_commits:,} "
              f"(commits in step1_commits.excluded=0 with no rows in step2_classes; "
              f"NOT folded into MbCanonFailures because units differ -- commits vs. class versions)")

    all_v = _vi(v, "MbListAllClassVersions")
    exp_v = _vi(v, "MbListExperimentVersions")
    check("Step2: experiment + non-experiment == all",
          exp_v + _vi(v, "MbListNonExperimentVersions"), all_v)

    if pilot_enabled:
        # Step 3 was run in *pilot* mode: it processes only a bounded
        # sample of experiment classes per commit (see run_settings for
        # PILOT_* keys). The full-population invariant
        # ``produced + failures == MbListExperimentVersions`` therefore
        # does NOT apply. Instead we verify that every commit Step 3
        # was supposed to walk finished successfully.
        complete = step3_progress.get("complete", 0)
        total_progress = sum(step3_progress.values())
        print("  [INFO] Step 3 was run in PILOT mode "
              f"({', '.join(f'{k}={v!r}' for k, v in sorted(pilot.items()))}); "
              "full-population Step-3 invariant is skipped.")
        check("Step3 (pilot): all walked commits complete",
              complete, total_progress)
        check("Step3 (pilot): walked commits == Step1 retained",
              total_progress, retained)
    else:
        check("Step3: produced + failures == experiment versions",
              _vi(v, "MbCanonProducedVersions") + _vi(v, "MbCanonFailures"), exp_v)

    cat_sum = sum(categories.values())
    check("Failure categories sum == MbCanonFailures",
          cat_sum, _vi(v, "MbCanonFailures"))

    pkg_load = categories.get("Package load failure", 0)
    if extra_load and pkg_load < extra_load:
        fails.append("Package-load category < commit-level load failures")
        print(f"  [FAIL] Package-load category ({pkg_load:,}) "
              f"< folded-in commit-level failures ({extra_load:,})")
    else:
        print(f"  [OK  ] Package-load category includes folded-in "
              f"commit-level failures ({extra_load:,})")

    return len(fails)


